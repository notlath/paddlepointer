CREATE FUNCTION public.revoke_auth_sessions_on_access_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.role IS DISTINCT FROM OLD.role OR (OLD.is_active AND NOT NEW.is_active) THEN
    DELETE FROM public.session WHERE user_id = NEW.id;
  END IF;
  RETURN NEW;
END;
$$;--> statement-breakpoint
CREATE TRIGGER revoke_auth_sessions_on_access_change
AFTER UPDATE OF role, is_active ON public."user"
